#' Build the memoised scraping worker for one host
#'
#' The worker is memoised with the host's own cache and is keyed only on the
#' semantic ingredients of a request (final URL including query parameters,
#' user-agent, accepted type, content override and retry count), so a cache
#' hit can only happen for a request that is semantically identical, and is
#' never shared across hosts. The rate limiter, handle and config are taken
#' from the host state at call time.
#'
#' @param st per-host state environment created by `polite_host()`
#'
#' @return memoised function performing the actual (rate-limited) GET
#' @keywords internal
#' @importFrom memoise memoise
make_host_scraper <- function(st){
  f <- function(url, user_agent, accept, content, times, verbose){
    response <- st$get(url, st$config, st$handle, times, verbose)

    if (httr::http_error(response)) {
      warning(httr::http_status(response)$message, " ", url, call. = FALSE)
      return(NULL)
    }

    content <- content %otherwise% response$headers$`content-type`

    res <- tryCatch(
      {
        httr::content(response, type = content)
      },
      error = function(cond) {
        warning(
          paste0(
            "<polite session> Encountered an error while parsing content.\n",
            "There seems to be a mismatch of content type or encoding or both.\n",
            "The server says it is serving:",
            response$headers$`content-type`,
            "\n",
            "Here's the text of the error generated by httr::content(): \n",
            cond,
            "\n",
            "Returning raw vector which can be parsed with rawToChar(). Good luck!\n"
          ),
          call. = FALSE
        )
        return(httr::content(response, as = "raw"))
      }
    )
    res
  }
  memoise::memoise(f, cache = st$cache)
}


#' @importFrom httr http_error content modify_url parse_url
m_scrape <- function(
  bow,
  query = NULL,
  params = NULL,
  accept = "html",
  content = NULL,
  verbose = FALSE
) {
  # nolint

  if (!inherits(bow, "polite")) {
    stop("Please be polite: bow then scrape!")
  }

  stopifnot(is.list(query) || is.null(query))

  if (!is.null(query)) {
    bow$url <- httr::modify_url(bow$url, query = query)
  } else {
    if (!is.null(params)) {
      warning(
        "Argument `params` is deprecated. Please, use `query` passing parameters as a named list.",
        call. = FALSE
      )
      params <- gsub("^.*\\?", "", params) # this will delete url prefix if any
      query <- httr::parse_url(paste0(
        "http://www.example.com/q?",
        params
      ))$query
      bow$url <- httr::modify_url(bow$url, query = query)
    }
  }

  if (!is_scrapable(bow)) {
    warning("No scraping allowed here!", call. = FALSE)
    return(NULL)
  }

  if (substr(accept, 1, 1) != "." && !grepl("/", accept)) {
    accept <- paste0("example.", accept)
  }

  accept_type <- httr::accept(accept)
  bow$config <- c(bow$config, accept_type)

  # dispatch through the rate limiter and cache belonging to this host
  st <- polite_host(bow$domain)
  st$config <- bow$config
  st$handle <- bow$handle
  if (is.null(st$scrape))
    st$scrape <- make_host_scraper(st)

  st$scrape(bow$url, bow$user_agent, accept, content, bow$times, verbose)
}


#' Scrape the content of authorized page/API
#'
#' @param bow host introduction object of class `polite`, `session` created by `bow()` or `nod()`
#' @param query named list of parameters to be appended to URL in the format `list(param1=valA, param2=valB)`
#' @param params deprecated. Use `query` argument above.
#' @param accept character value of expected data type to be returned by host (e.g. `html`, `json`, `xml`, `csv`, `txt`, etc.)
#' @param content MIME type (aka internet media type) used to override the content type returned by the server.
#' See http://en.wikipedia.org/wiki/Internet_media_type for a list of common types. You can add the `charset` parameter to override the server's default encoding
#' For example, you could write `content="text/html; charset=UTF-8"`
#' @param verbose extra feedback from the function. Defaults to `FALSE`
#'
#' @return Object of class `httr::response` which can be further processed by functions in `rvest` package
#'
#' @examples
#' \donttest{
#'  library(rvest)
#'   bow("https://en.wikipedia.org/wiki/List_of_cognitive_biases") %>%
#'    scrape(content="text/html; charset=UTF-8") %>%
#'    html_nodes(".wikitable") %>%
#'    html_table()
#'}
#'
#' @export
scrape <- memoise::memoise(m_scrape)
